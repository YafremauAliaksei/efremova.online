#!/bin/sh
# ═══════════════════════════════════════════════════════════════════════
#  Ротация и удаление логов nginx — срок хранения 14 дней.
#
#  В логах nginx — IP, User-Agent и адреса страниц посетителей, то есть
#  персональные данные. Политика конфиденциальности обещает 14 дней
#  (docs/03 п.11.2), значит, через 14 дней их не должно быть на диске.
#
#  Способ — copytruncate: файл копируется под датой и обнуляется. nginx
#  открывает логи с O_APPEND и после обнуления продолжает писать с начала,
#  так что сигнал nginx не нужен — а из соседнего контейнера его и не
#  послать. Между копией и обнулением может потеряться несколько строк;
#  для журнала доступа это приемлемо.
#
#  Отдельный скрипт, а не часть backup.sh: сбой выгрузки бэкапа не должен
#  оставлять логи на диске дольше обещанного.
# ═══════════════════════════════════════════════════════════════════════
set -eu

LOG_DIR="${NGINX_LOG_DIR:-/logs/nginx}"
RETENTION_DAYS="${NGINX_LOG_RETENTION_DAYS:-14}"

# Запуск сразу после полуночи UTC: содержимое — за прошедшие сутки
DAY="$(date -u -d "@$(($(date -u +%s) - 86400))" +%Y%m%d)"

for name in access error; do
  file="${LOG_DIR}/${name}.log"
  if [ -s "${file}" ]; then
    cp "${file}" "${LOG_DIR}/${name}-${DAY}.log"
    : > "${file}"
  fi
done

# -mtime +N — старше N полных суток
find "${LOG_DIR}" -type f -name '*-[0-9]*.log' -mtime +"$((RETENTION_DAYS - 1))" -exec rm -f {} \;

echo "[$(date -u)] Логи nginx: ротация за ${DAY}, хранение ${RETENTION_DAYS} дней"
