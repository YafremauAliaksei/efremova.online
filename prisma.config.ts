import { defineConfig } from 'prisma/config';

/**
 * Prisma 7 больше не читает .env сама — это делаем мы.
 *
 * Отдельная библиотека (dotenv) для этого не нужна: Node умеет читать .env
 * встроенными средствами начиная с 20.6, а у нас в engines указано >=22.
 * Каждая несъеденная зависимость — одна невыданная дверь (CLAUDE.md, правило 8).
 *
 * В CI файла .env нет и быть не должно: переменные приходят из настроек задачи.
 * Поэтому отсутствие файла — не ошибка, а ожидаемый случай.
 */
try {
  process.loadEnvFile('.env');
} catch {
  // .env отсутствует — значит, работаем в CI или в контейнере.
}

/**
 * Настройки командной строки Prisma.
 *
 * ── Зачем этот файл появился ──────────────────────────────────────────────
 *
 * До версии 7 адрес базы данных был записан прямо в prisma/schema.prisma
 * строкой `url = env("DATABASE_URL")`, а путь к схеме и команда заливки
 * демо-данных лежали в package.json в разделе "prisma". Седьмая версия
 * убрала и то, и другое: схема описывает структуру данных, а куда
 * подключаться — вопрос окружения, а не структуры.
 *
 * Для нас это изменение к лучшему. Файл схемы лежит в публичном репозитории,
 * и теперь в нём физически нет места, куда можно случайно вписать настоящий
 * адрес базы с паролем.
 *
 * ── Что важно понимать про этот файл ──────────────────────────────────────
 *
 * Он нужен ТОЛЬКО командам prisma: migrate, studio, db seed. Приложение его
 * не читает — оно подключается к базе через адаптер драйвера в src/lib/db.ts.
 * То есть настроек подключения стало два места, и это не дублирование:
 * инструменты разработчика и работающий сайт живут в разных условиях
 * (миграции запускают с машины разработчика, сайт — внутри контейнера).
 *
 * ── Секреты ───────────────────────────────────────────────────────────────
 *
 * env('DATABASE_URL') читает переменную окружения. Настоящее значение живёт
 * только в .env, который в .gitignore (CLAUDE.md, правило 1). В этом файле
 * есть имя переменной, но не её содержимое.
 */
/**
 * Адрес базы нужен НЕ всем командам.
 *
 * `prisma generate` только читает схему и пишет типы — база ему не нужна.
 * Именно так собирается Docker-образ: без доступа к базе, и это правильно.
 * А вот `migrate` и `studio` без адреса работать не могут.
 *
 * Поэтому блок datasource добавляется только когда переменная задана.
 * Прежний вариант — env('DATABASE_URL') — падал на этапе сборки образа
 * с ошибкой «Cannot resolve environment variable», хотя ничего плохого
 * не происходило: переменной там просто неоткуда взяться.
 */
const databaseUrl = process.env.DATABASE_URL;

export default defineConfig({
  schema: 'prisma/schema.prisma',

  ...(databaseUrl === undefined ? {} : { datasource: { url: databaseUrl } }),

  migrations: {
    // Демо-данные для локальной разработки. Прод-базу этим не наполняют:
    // содержимое сайта правится через админку (CLAUDE.md, правило 4).
    seed: 'tsx prisma/seed.ts',
  },
});
