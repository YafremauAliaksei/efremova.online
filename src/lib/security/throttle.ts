/**
 * 🚦 Ограничитель записи событий безопасности.
 *
 * ═══════════════════════════════════════════════════════════════════════════
 *  ЗАЧЕМ ЭТО СУЩЕСТВУЕТ
 *
 *  Ловушки устроены так: попался — ждём 2–5 секунд и записываем событие.
 *  Пока стучится одиночный сканер, это работает. Но при массовой атаке
 *  каждое из трёх действий превращается в оружие ПРОТИВ нас:
 *
 *    1. Запись события — это ещё один HTTP-запрос к самим себе.
 *       1000 запросов снаружи превращались в 2000 внутри: атака удваивалась.
 *    2. Задержка 2–5 секунд держит соединение и таймер. Через пять секунд
 *       атаки в 1000 запросов в секунду висит 5000 соединений — лимит
 *       кончится у нас раньше, чем терпение у атакующего.
 *    3. Каждое попадание — строка в базе и строка в логе.
 *
 *  Отдельная ирония по пункту 2: задержка задумывалась, чтобы тратить время
 *  сканера. Но сканер не ждёт ответа — он шлёт следующий запрос немедленно.
 *  Ждём мы, своими соединениями.
 *
 *  Этот модуль ставит три независимых предела. Пробить нужно все три сразу,
 *  а они устроены по-разному.
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * ── ПОЧЕМУ ЭТО ЧИСТАЯ ЛОГИКА БЕЗ ПОБОЧНЫХ ЭФФЕКТОВ ─────────────────────────
 *
 * Ни базы, ни сети, ни глобальных переменных внутри — только состояние,
 * созданное вызывающим. Благодаря этому поведение проверяется тестами
 * с подставным временем, а не «посмотрим в проде под атакой».
 *
 * ── ЧТО БУДЕТ, ЕСЛИ СОСТОЯНИЕ ПОТЕРЯЕТСЯ ───────────────────────────────────
 *
 * Состояние живёт в памяти процесса. При перезапуске оно обнуляется, при
 * нескольких экземплярах приложения у каждого своё. Это осознанно: точность
 * здесь не нужна, нужен ПОТОЛОК. Худшее последствие потери — несколько лишних
 * записей, а не пропущенная атака: сама защита от ловушек работает всегда,
 * ограничитель управляет только тем, что мы записываем и как долго ждём.
 */

/** Что делать с этим попаданием */
export interface ThrottleDecision {
  /** Отправлять ли событие на запись */
  report: boolean;
  /**
   * Сколько попаданий накопилось с прошлой отправки, включая текущее.
   * Уходит в базу одним числом.
   *
   * ⚠️ Честная оговорка: накопленное отправляется вместе со СЛЕДУЮЩЕЙ
   * записью. Если поток оборвался, хвост последнего окна в базу не попадёт.
   * Это принято сознательно: задача — увидеть атаку и её порядок величины,
   * а не вести точный учёт. Ради точного счёта пришлось бы держать таймер
   * на каждый адрес, то есть вернуть ту самую нагрузку, от которой
   * ограничитель и защищает.
   */
  count: number;
  /** Задерживать ли ответ. Задержка только там, где есть отправка */
  delayMs: number;
}

export interface ThrottleOptions {
  /** Не чаще одной отправки на ключ за это время */
  perKeyIntervalMs?: number;
  /** Потолок отправок в минуту по ВСЕМ ключам сразу */
  maxReportsPerMinute?: number;
  /** Сколько ключей держим в памяти. Больше — вытесняем самый старый */
  maxTrackedKeys?: number;
}

interface KeyState {
  /** Накоплено с прошлой отправки */
  pending: number;
  lastReportAt: number;
}

export interface Throttle {
  register(key: string, now: number, delayMs: number): ThrottleDecision;
  /** Сколько ключей сейчас отслеживается — для тестов и диагностики */
  size(): number;
  /** Сколько отправок отброшено общим потолком с начала текущей минуты */
  droppedThisMinute(): number;
}

const DEFAULTS = {
  // Минуты достаточно: интересен факт атаки и её масштаб, а не каждый запрос
  perKeyIntervalMs: 60_000,
  // 120 записей в минуту — это две в секунду. Для разбора хватает с запасом,
  // а диск за такой темп не забить при любой продолжительности атаки.
  maxReportsPerMinute: 120,
  // 5000 ключей — несколько сотен килобайт памяти. Потолок нужен, потому что
  // при распределённой атаке ключей столько же, сколько адресов в ботнете.
  maxTrackedKeys: 5000,
} as const;

export function createThrottle(options: ThrottleOptions = {}): Throttle {
  const perKeyIntervalMs = options.perKeyIntervalMs ?? DEFAULTS.perKeyIntervalMs;
  const maxReportsPerMinute = options.maxReportsPerMinute ?? DEFAULTS.maxReportsPerMinute;
  const maxTrackedKeys = options.maxTrackedKeys ?? DEFAULTS.maxTrackedKeys;

  // Map в JavaScript хранит ключи в порядке добавления — это позволяет
  // вытеснять самый старый без отдельной структуры данных.
  const keys = new Map<string, KeyState>();

  let minuteStart = 0;
  let reportsThisMinute = 0;
  let dropped = 0;

  function rollMinute(now: number): void {
    if (now - minuteStart >= 60_000) {
      minuteStart = now;
      reportsThisMinute = 0;
      dropped = 0;
    }
  }

  return {
    register(key, now, delayMs) {
      rollMinute(now);

      const existing = keys.get(key);

      // ─── Предел 1: не чаще одной отправки на ключ за интервал ───
      if (existing !== undefined && now - existing.lastReportAt < perKeyIntervalMs) {
        existing.pending += 1;
        // Ни отправки, ни задержки: ответ 404 уходит мгновенно.
        // Это и есть главная защита — повторный запрос стоит нам почти ничего.
        return { report: false, count: 0, delayMs: 0 };
      }

      // ─── Предел 2: общий потолок отправок в минуту ───
      //
      // Нужен отдельно от первого: при распределённой атаке каждый адрес
      // новый, предел на ключ его не ловит. Здесь ловится.
      if (reportsThisMinute >= maxReportsPerMinute) {
        dropped += 1;
        if (existing !== undefined) existing.pending += 1;
        return { report: false, count: 0, delayMs: 0 };
      }

      // ─── Предел 3: сколько ключей держим в памяти ───
      //
      // Вытесняем самый старый, а не отказываемся отслеживать новый:
      // при атаке новые адреса важнее давно молчащих.
      if (existing === undefined && keys.size >= maxTrackedKeys) {
        const oldest = keys.keys().next();
        if (!oldest.done) keys.delete(oldest.value);
      }

      const count = (existing?.pending ?? 0) + 1;
      keys.set(key, { pending: 0, lastReportAt: now });
      reportsThisMinute += 1;

      return { report: true, count, delayMs };
    },

    size: () => keys.size,
    droppedThisMinute: () => dropped,
  };
}

/**
 * Ключ склейки: адрес плюс тип ловушки.
 *
 * Тип, а не конкретный путь: сканер перебирает сотни путей одного типа,
 * и склеивать их по отдельности означало бы сотни строк вместо одной.
 */
export function throttleKey(ip: string, trapType: string): string {
  return `${ip}|${trapType}`;
}

/** Начало часа в UTC — граница склейки записей в базе */
export function hourBucket(now: Date): Date {
  const bucket = new Date(now);
  bucket.setUTCMinutes(0, 0, 0);
  return bucket;
}
