import 'server-only';
import { createHash, timingSafeEqual } from 'node:crypto';
import { env } from '@/lib/env';

/**
 * Проверка, что запрос пришёл от нашего же middleware, а не снаружи.
 *
 * ── ЗАЧЕМ ЭТО ВООБЩЕ ─────────────────────────────────────────────────────
 *
 * Обработчики /api/internal/* пишут в журнал безопасности. Если пустить туда
 * кого угодно, получится инструмент для двух атак сразу:
 *
 *   • забить базу мусором (тот самый отказ в обслуживании через механизм
 *     защиты, ради которого писался ограничитель);
 *   • НАПИСАТЬ ЛОЖЬ в журнал — подсунуть чужие адреса, чтобы утопить
 *     настоящую атаку в шуме или подставить непричастных.
 *
 * Второе опаснее: испорченному журналу нельзя верить, а значит его как бы
 * и нет.
 *
 * ── ПОЧЕМУ СРАВНЕНИЕ ХЕШЕЙ, А НЕ СТРОК ───────────────────────────────────
 *
 * Обычное сравнение строк (a === b) заканчивается на первом несовпавшем
 * символе. Замеряя время ответа, значение можно подобрать посимвольно —
 * это атака по времени. timingSafeEqual сравнивает за одинаковое время
 * независимо от того, где именно различие.
 *
 * Сравниваются именно ХЕШИ, а не сами значения: timingSafeEqual требует
 * равной длины буферов и падает при разной, а сам факт «длина не совпала»
 * — уже подсказка атакующему. SHA-256 всегда даёт 32 байта.
 */

const INTERNAL_HEADER = 'x-internal-token';

export function isInternalRequest(request: Request): boolean {
  const secret = env().AUTH_SECRET;

  // Секрет не задан — внутренние обработчики просто не работают.
  // Это безопаснее, чем «пустой пароль подходит».
  if (secret === undefined || secret.length === 0) return false;

  const provided = request.headers.get(INTERNAL_HEADER);
  if (provided === null || provided.length === 0) return false;

  const a = createHash('sha256').update(provided).digest();
  const b = createHash('sha256').update(secret).digest();

  return timingSafeEqual(a, b);
}
