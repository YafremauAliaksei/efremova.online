import 'server-only';
import { PrismaPg } from '@prisma/adapter-pg';
import { PrismaClient } from '@prisma/client';

/**
 * Единственный экземпляр клиента базы данных.
 *
 * ── Почему здесь появился адаптер ─────────────────────────────────────────
 *
 * До Prisma 7 клиент сам знал адрес базы: он читал строку `url` из схемы.
 * Седьмая версия это убрала — теперь подключением занимается адаптер драйвера,
 * которому строка передаётся здесь, в коде приложения.
 *
 * Для проекта с медицинскими данными это скорее плюс: адрес базы вместе
 * с паролем больше не может попасть в prisma/schema.prisma, то есть в файл,
 * лежащий в публичном репозитории.
 *
 * ── Почему конфигурация пула, а не готовая строка ─────────────────────────
 *
 * PrismaPg принимает и строку подключения, и объект настроек. Выбран объект,
 * потому что `connectionString` в нём НЕОБЯЗАТЕЛЕН. Это сохраняет прежнее
 * поведение: сборка Next.js импортирует этот модуль, и она обязана проходить
 * без доступа к базе — именно так собирается задача Lighthouse в конвейере,
 * где DATABASE_URL не задаётся вовсе. Соединение устанавливается лениво,
 * при первом запросе, и падает тогда же, а не при импорте.
 *
 * ── Почему глобальная переменная ──────────────────────────────────────────
 *
 * В режиме разработки Next.js перезагружает модули при каждом изменении файла.
 * Без этой защиты за час работы накопились бы сотни подключений, и PostgreSQL
 * отказал бы в новых.
 */
const globalForPrisma = globalThis as unknown as { prisma?: PrismaClient };

export const db =
  globalForPrisma.prisma ??
  new PrismaClient({
    adapter: new PrismaPg({ connectionString: process.env.DATABASE_URL }),
    // В проде пишем только ошибки: запросы могут содержать персональные данные
    log: process.env.NODE_ENV === 'development' ? ['warn', 'error'] : ['error'],
  });

if (process.env.NODE_ENV !== 'production') {
  globalForPrisma.prisma = db;
}
